DROP TABLE "CATEGORIES" CASCADE CONSTRAINTS;
CREATE TABLE "CATEGORIES" (
 "ID" NUMBER(10) NOT NULL PRIMARY KEY,
 "NAME" VARCHAR2(400) NOT NULL,
 "DESCRIPTION" VARCHAR2(400)
);


DROP TABLE "TABLES" CASCADE CONSTRAINTS;
CREATE TABLE "TABLES" (
 "ID" NUMBER(10) NOT NULL PRIMARY KEY,
 "TABLE_NO" NUMBER(10) NOT NULL,
 "STATUS" VARCHAR2(400) NOT NULL,

 CONSTRAINT TABLES_TABLE_NO_UQ UNIQUE("TABLE_NO")
);


DROP TABLE "USERS" CASCADE CONSTRAINTS;
CREATE TABLE "USERS" (
 "ID" NUMBER(10) NOT NULL PRIMARY KEY,
 "LOGIN_ID" VARCHAR2(400) NOT NULL,
 "PASSWORD" VARCHAR2(400) NOT NULL,
 "NAME" VARCHAR2(400) NOT NULL,
 "ROLE" VARCHAR2(400) NOT NULL,
 "STATUS" VARCHAR2(400) NOT NULL,
 "CREATED_DATETIME" DATE NOT NULL,

 CONSTRAINT USERS_LOGIN_ID_UQ UNIQUE("LOGIN_ID")
);


DROP TABLE "PRODUCTS" CASCADE CONSTRAINTS;
CREATE TABLE "PRODUCTS" (
 "ID" NUMBER(10) NOT NULL PRIMARY KEY,
 "CATEGORY_ID" NUMBER(10) NOT NULL,
 "NAME" VARCHAR2(400) NOT NULL,
 "SIZE_NAME" VARCHAR2(400),
 "PRICE" NUMBER(10) NOT NULL,
 "TAX_RATE" NUMBER(10) NOT NULL,
 "SALES_STATUS" VARCHAR2(400) NOT NULL,
 "DESCRIPTION" VARCHAR2(400),
 "IMAGE_URL" VARCHAR2(400),

 FOREIGN KEY ("CATEGORY_ID") REFERENCES "CATEGORIES" ("ID")
);


DROP TABLE "PRODUCT_TOPPINGS" CASCADE CONSTRAINTS;
CREATE TABLE "PRODUCT_TOPPINGS" (
 "ID" NUMBER(10) NOT NULL PRIMARY KEY,
 "PRODUCT_ID" NUMBER(10) NOT NULL,
 "TOPPING_PRODUCT_ID" NUMBER(10) NOT NULL,

 FOREIGN KEY ("PRODUCT_ID") REFERENCES "PRODUCTS" ("ID"),
 FOREIGN KEY ("TOPPING_PRODUCT_ID") REFERENCES "PRODUCTS" ("ID"),

 CONSTRAINT PRODUCT_TOPPINGS_UQ UNIQUE("PRODUCT_ID","TOPPING_PRODUCT_ID")
);


DROP TABLE "ORDERS" CASCADE CONSTRAINTS;
CREATE TABLE "ORDERS" (
 "ID" NUMBER(10) NOT NULL PRIMARY KEY,
 "TABLE_ID" NUMBER(10) NOT NULL,
 "GUEST_COUNT" NUMBER(10) NOT NULL,
 "VISIT_DATETIME" DATE NOT NULL,
 "PAYMENT_DATETIME" DATE,
 "PAYMENT_STATUS" VARCHAR2(400) NOT NULL,
 "PAYMENT_METHOD" VARCHAR2(400),
 "TOTAL_AMOUNT" NUMBER(10) NOT NULL,

 FOREIGN KEY ("TABLE_ID") REFERENCES "TABLES" ("ID")
);


DROP TABLE "ORDER_DETAILS" CASCADE CONSTRAINTS;
CREATE TABLE "ORDER_DETAILS" (
 "ID" NUMBER(10) NOT NULL PRIMARY KEY,
 "ORDER_ID" NUMBER(10) NOT NULL,
 "PRODUCT_ID" NUMBER(10) NOT NULL,
 "ORIGINAL_ORDER_DETAIL_ID" NUMBER(10),
 "QUANTITY" NUMBER(10) NOT NULL,
 "SALE_PRICE" NUMBER(10) NOT NULL,
 "ORDER_STATUS" VARCHAR2(400) NOT NULL,
 "ORDERED_DATETIME" DATE NOT NULL,
 "COOKED_DATETIME" DATE,
 "USER_ID" NUMBER(10),
 "CANCELED_DATETIME" DATE,

 FOREIGN KEY ("ORDER_ID") REFERENCES "ORDERS" ("ID"),
 FOREIGN KEY ("PRODUCT_ID") REFERENCES "PRODUCTS" ("ID"),
 FOREIGN KEY ("ORIGINAL_ORDER_DETAIL_ID") REFERENCES "ORDER_DETAILS" ("ID"),
 FOREIGN KEY ("USER_ID") REFERENCES "USERS" ("ID")
);


DROP TABLE "TERMINAL_SETTINGS" CASCADE CONSTRAINTS;
CREATE TABLE "TERMINAL_SETTINGS" (
 "ID" NUMBER(10) NOT NULL PRIMARY KEY,
 "TABLE_ID" NUMBER(10),
 "CODE" VARCHAR2(400) NOT NULL,
 "NAME" VARCHAR2(400) NOT NULL,
 "TYPE" VARCHAR2(400) NOT NULL,

 FOREIGN KEY ("TABLE_ID") REFERENCES "TABLES" ("ID"),

 CONSTRAINT TERMINAL_SETTINGS_CODE_UQ UNIQUE("CODE"),
 CONSTRAINT TERMINAL_SETTINGS_TABLE_ID_UQ UNIQUE("TABLE_ID")
);


